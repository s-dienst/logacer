function th_h_a_link_type($link_value, $args = false) {
    $language = 'FR';
    if ($args === 'multiple') {
        $language .= '_m';
    }
    if ($link_value === false) {
        return LINKS_HOR_TYPE['not_linked'][$language];
    } elseif (isset(LINKS_HOR_TYPE[$link_value][$language])) {
        return LINKS_HOR_TYPE[$link_value][$language];
    } else {
        return LINKS_HOR_TYPE['undescribed'][$language];
    }
}

