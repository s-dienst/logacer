 ### 4\. Une ressource grecque que je placerais très haut

 La base **Imported Pottery in the Peloponnese and Crete** est particulièrement intéressante et avait été insuffisamment mise en avant dans ma première réponse : elle contient **plus de 5 800 enregistrements**, un SIG, et couvre les importations céramiques du **IVe au XVe/XVIe siècle**. Pour ton intervalle IVe–VIIe siècle, elle est donc directement exploitable.  helios.eie.gr+1

 ### 5\. Le corpus britannique « Late Roman Britain » est quantitativement exceptionnel

 Le dataset issu des travaux sur les mouvements de céramique en Bretagne romaine rassemble **plus de deux millions de tessons provenant de 775 fouilles et 652 sites**, avec 49 industries identifiées. Ce n'est pas une typologie universelle, mais pour les questions de **production, diffusion, consommation et économie**, c'est une ressource majeure.  DOI

