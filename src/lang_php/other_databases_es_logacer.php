 Quelques précautions méthodologiques :

 - **50 entrées** ci-dessous, plutôt que 100 entrées artificiellement gonflées avec chaque petit dataset de fouille de l’ADS.
- Le champ « nombre » donne le nombre d’objets, tessons, notices ou enregistrements **lorsqu'il est documenté** ; « NR » signifie que je n’ai pas trouvé de chiffre fiable.
- **Pertinence** :\
   **★★★★★** = directement incontournable pour Rome / Antiquité tardive / VIIe s. ;\
   **★★★★☆** = très importante mais régionale ou spécialisée ;\
   **★★★☆☆** = utile en complément ;\
   **★★☆☆☆** = intérêt contextuel ou chronologique limité ;\
   **★☆☆☆☆** = essentiellement comparative.
- « Accès » indique l'état actuel, pas nécessairement le statut juridique de réutilisation des données.
- J’ai volontairement conservé quelques **projets archivés mais toujours accessibles**, car ils ont une valeur scientifique réelle pour une recension. L’ADS est particulièrement important à cet égard : il conserve de nombreux anciens projets sous forme de datasets téléchargeables.  Archaeology Data Service+1

