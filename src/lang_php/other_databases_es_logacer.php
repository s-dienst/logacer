<h2>Autres bases de données dédiées à la céramique romaine et tardo-antique</h2>

<h3>Amphores</h3>

    <h4>PIRIDI - Prosopographia Imperii Romani Instrumentum Domesticum Inscriptum</h4>
    <p>
        La plateforme de recherche PIRIDI, développée autour de Piero Berni Millet, est bâtie autour d'une volontée de lier les artefacts archéologiques aux auteurs des inscriptions qui y sont retrouvées.
        Son outil principal actuel est une base de données relationnelle centrée sur les inscriptions trouvées sur les amphores romaines, en particulier les Dressel 20 du Monte Testaccio.
    </p>
    <p>
        <a href="https://piridi.net/">Lien vers le projet</a>
    </p>

    <h4>Roman Amphorae</h4>
    <p>
        Cette base de données, développée par l'University of Southampton, constitue un référentiel essentiel concernant les amphores romaines et tardo-antiques, allant de la fin du IIIe s. av. J.-C. au VIIe s. ap. J.-C.
        Chaque type d'amphore est accompagné d'informations morphologiques, chronologiques, géographiques (origine et distribution), sur le contenu supposé. Des dessins et photographies (d'amphores, de pâtes ou de lames minces) accompagnent de très nombreuses fiches.
        La base de données est maintenant archivée au sein de l'Archaeology Data Service.
    </p>
    <p>
        <a href="https://archaeologydataservice.ac.uk/archives/view/amphora_ahrb_2005/index.cfm">Lien vers la base de données</a>
    </p>

    <h4>Amphorae ex Hispania</h4>
    <p>
        Ce projet, géré par l'ICAC (Institut Català d'Arqueologia Clàssica), est un réseau de laboratoires virtuels ayant notamment produit une base de données centrée sur les amphores de la Péninsule ibérique.
        Chaque type d'amphore, calssé par zone de production, est longuement documenté, avec ses caractéristiques, sa production, sa distribution, l'épigraphie, son contenu avéré ou supposé et les données archéométriques et une bibliographie.
    </p>
    <p>
        <a href="https://amphorae.icac.cat/">Lien vers le projet</a>
    </p>

<h3>Terres sigillées</h3>

    <h4>Samian Navigator</h4>
    <p>
        Base de données gérée par le LEIZA (Leibniz-Zentrum für Archäologie) et consacrée principalement à la terre sigillée, avec des données
        sur les potiers, estampilles, formes, poinçons, décors, ateliers et sites de découverte.
    </p>
    <p>
        <a href="https://www1.leiza.de/samian/home/navitree.cfm">Lien vers la base de données</a>
    </p>

    <h4>ARS3D African Red Slip Ware digitalised</h4>
    <p>
        Base de données issue d'un projet du LEIZA (Leibniz-Zentrum für Archäologie) et de la Johannes Gutenberg-Universität Mainz, modélisant en 3D la terre sigillée africaine.
        La base de données ne semble plus accessible en ligne, mais le projet est disponible sur <a href="https://gitlab.rlp.net/ars3d">GitLab</a> et les données sur <a href="https://github.com/RGZM/ars-lod">GitHub</a> et <a href="https://zenodo.org/records/5646898">Zenodo</a>.
    </p>
    <p>
        <a href="https://www.leiza.de/en/research/project-6/ars3d-african-red-slip-ware-digitalised">Description du projet</a>
    </p>

<h3>Études de pâtes et projets archéométriques</h3>

    <h4>FACEM - Fabrics of Ancient Ceramics in the Mediterranean</h4>
    <p>
        Cette base de données, financée par le FWF (Fonds zur Förderung der wissenschaftlichen Forschung, Autriche) présente des groupes de pâtes issus de diverses régions de Méditerranée.
        Pour chacun d'entre eux, des photographies des cassures fraîches sont disponible, ainsi que les sites de production supposée et de découverte, une description de la pâte et de l'artefact, d'autres données archéométriques et une bibliographie.
        En 2026, une refonte de la base de données était signalée comme prévue.
    </p>
    <p>
        <a href="https://facem.at/">Lien vers la base de données</a>
    </p>

<h3>Zones géographiques</h3>

    <h4>ICRATES - Inventory of Crafts and Trade in the Roman East</h4>
    <p>
        ICRATES est une base de données gérée par Philip Bes, Rinse Willet, Jeroen Poblome et Tom Brughmans, recensant 33'939 artefacts (tessons de céramique de table) retrouvés dans 275 sites répartis sur le pourtour méditerranéen oriental.
        Pour chaque artefact, la location est indiquée, la publication originale, le dépôt, ainsi que des informations sur les formes et estampilles.
        La base de données a été archivée en 2019 sur l'ADS et y est consultable. Elle est en outre entièrement téléchargeable sous format CSV.
    </p>
    <p>
        <a href="https://archaeologydataservice.ac.uk/archives/view/icrates_lt_2018/index.cfm">Lien vers la base de données</a>
    </p>

    <h4>LCP - Levantine Ceramics Project</h4>
    <p>
        Le Levantine Ceramics Project est une base de données open-access développée sous l'égide de l'ASOR (American Society of Overseas Research). Elle contient des informations sur la céramique produite entre le néolithique et la période ottomane dans les régions modernes de Turquie, Syrie, Liban, Chypre, Israel, Jordanie, Palestine et Egypte.
        Les informations regroupées concernant tant la céramique (avec sa description et des illustrations) que les catégories, groupes de pâtes, études archéométriques, fours et ateliers, ainsi qu'une importante bibliographie.
        Le projet est alimenté par plusieurs centaines de contributeur, pour plusieurs dizaines de milliers d'enregistrements.
    </p>
    <p>
        <a href="https://www.levantineceramics.org/">Lien vers le projet</a>
    </p>

<h3>Projets génériques</h3>

    <h4>Potsherd – Atlas of Roman Pottery</h4>
    <p>
        Potsherd est un atlas géré par P.A. Tyers et regroupant des informations sur de nombreuses catégories et productions de céramique romaine, particulièrement entre le 1er et le 5e s. ap. J.-C.
        La Grande-Bretagne est particulièrement bien représentée, faisant suite au projet <i>Roman Pottery in Britain</i>, mais l'atlas comporte des entrées pertinentes pour l'ensemble de l'Europe occidentale.
        Des cartes de distribution ont été développées en 2022 pour accompagner le catalogue des catégories et productions.
    </p>
    <p>
        <a href="https://potsherd.net/home/">Lien vers la base de données</a>
    </p>

